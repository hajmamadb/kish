def _rtl(r):
    r._element.get_or_add_rPr().append(OxmlElement("w:rtl"))

def _bidi(p):
    p._p.get_or_add_pPr().append(OxmlElement("w:bidi"))

def para(doc, text="", size=10, color=DARK, bold=False, italic=False,
         align=WD_ALIGN_PARAGRAPH.RIGHT, before=0, after=4, line=1.15):
    p = doc.add_paragraph()
    _bidi(p)
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line
    if text:
        r = p.add_run(text)
        r.font.name = FONT
        r._element.rPr.rFonts.set(qn("w:cs"), FONT)
        r.font.size = Pt(size)
        r.font.color.rgb = color
        r.font.bold = bold
        r.font.italic = italic
        _rtl(r)
    return p

def run(p, text, size=10, color=DARK, bold=False, italic=False):
    r = p.add_run(text)
    r.font.name = FONT
    r._element.rPr.rFonts.set(qn("w:cs"), FONT)
    r.font.size = Pt(size)
    r.font.color.rgb = color
    r.font.bold = bold
    r.font.italic = italic
    _rtl(r)
    return r

def heading(doc, text, size=14, color=NAVY, before=14, after=6):
    return para(doc, text, size=size, color=color, bold=True, before=before, after=after)

def hline(doc):
    p = para(doc, "", after=2)
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "8")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "1F4E79")
    pbdr.append(bottom)
    pPr.append(pbdr)
    return p

